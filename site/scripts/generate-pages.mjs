export function loadSkills() {
	return fs
		.readdirSync(R('skills'))
		.sort()
		.filter((d) => fs.existsSync(R(`skills/${d}/SKILL.md`)))
		.map((d) => {
			const src = fs.readFileSync(R(`skills/${d}/SKILL.md`), 'utf8');
			// Some SKILL.md frontmatter is not strict YAML (an unquoted ": " in a description), and
			// agents read it line by line anyway — so do the same.
			const head = src.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? '';
			const fm = {};
			for (const line of head.split('\n')) {
				const m = line.match(/^(name|description):\s*(.*)$/);
				if (m) fm[m[1]] = m[2].replace(/^(["'])(.*)\1$/, '$2');
			}
			return { dir: d, name: fm.name ?? d, description: fm.description ?? '' };
		});
}

// ---------------------------------------------------------------------------
// CLI: the usage text `wfx help` prints, read from its one source
// ---------------------------------------------------------------------------

export function wfxUsage() {
	const src = fs.readFileSync(R('apps/api/cmd/wfx/main.go'), 'utf8');
	const m = src.match(/func usage\(\) \{\s*fmt\.Print\(`([\s\S]*?)`\)/);
	if (!m) throw new Error('could not find usage() in apps/api/cmd/wfx/main.go');
	return m[1];
}

/** Every `wfx <verb> [<sub>]` the usage text documents, e.g. "workflow approve", "runs". */
export function wfxCommands() {
	const cmds = new Set();
	for (const line of wfxUsage().split('\n')) {
		const m = line.match(/^\s+wfx ([a-z][a-z-]*)(?: ([a-z][a-z-]*))?/);
		if (!m) continue;
		cmds.add(m[1]);
		if (m[2]) cmds.add(`${m[1]} ${m[2]}`);
	}
	return cmds;
}

function cliPage() {
	const usage = wfxUsage();
	const groups = new Map();
	for (const line of usage.split('\n')) {
		const m = line.match(/^\s+(wfx ([a-z-]+)\S*(?: [^ ].*?)?)\s{2,}(.*)$/);
		if (!m) continue;
		const verb = m[2];
		if (!groups.has(verb)) groups.set(verb, []);
		groups.get(verb).push({ cmd: m[1].trim(), what: m[3].trim() });
	}
	let md = `---\ntitle: CLI reference\ndescription: Every wfx command, generated from the usage text that \`wfx help\` prints.\n---\n\n`;
	md += BANNER('apps/api/cmd/wfx/main.go (usage — the text `wfx help` prints)');
	md += `\nThis page is the output of \`wfx help\` on \`main\`, reorganised by verb. It is read from the\nsame string the binary prints, so a command that is not here does not exist.\n\n`;
	md += `## Verbatim\n\n\`\`\`text\n${usage.trim()}\n\`\`\`\n\n## By verb\n\n`;
	for (const [verb, rows] of [...groups].sort()) {
		md += `### \`wfx ${verb}\`\n\n| Command | What it does |\n|---|---|\n`;
		for (const r of rows) md += `| ${code(r.cmd)} | ${esc(r.what)} |\n`;
		md += `\n`;
	}
	return md;
}

// ---------------------------------------------------------------------------
// providers / classifiers registry
// ---------------------------------------------------------------------------

export function loadRegistry() {
	return JSON.parse(fs.readFileSync(R('registries.json'), 'utf8'));
}

function registryPage() {
	const reg = loadRegistry();
	const prov = Object.entries(reg.providers ?? {});
	const byKind = {};
	for (const [, p] of prov) byKind[p.kind] = (byKind[p.kind] ?? 0) + 1;
	let md = `---\ntitle: Provider registry\ndescription: Every provider and classifier registries.json ships, generated from the file.\n---\n\n`;
	md += BANNER('registries.json');
	md += `\n\`registries.json\` at the repo root ships **${prov.length} providers** (${Object.entries(byKind)
		.sort()
		.map(([k, n]) => `${n} \`${k}\``)
		.join(', ')}) and **${Object.keys(reg.classifiers ?? {}).length} classifiers**. A step names one with \`provider:\` /\n\`classifier:\`; a step that names none gets \`WFX_DEFAULT_PROVIDER\` / \`WFX_DEFAULT_CLASSIFIER\`.\n\n`;
	md += `## Providers\n\n| Name | Kind | Default model | Credential (env var name) | Notes |\n|---|---|---|---|---|\n`;
	for (const [name, p] of prov.sort(([a], [b]) => a.localeCompare(b))) {
		md += `| ${code(name)} | ${code(p.kind)}${p.preset ? ` (${code(p.preset)})` : ''} | ${p.model ? code(p.model) : ''} | ${p.apiKeyEnv ? code(p.apiKeyEnv) : ''} | ${esc(p.description ?? '')} |\n`;
	}
	md += `\n## Classifiers\n\n| Name | Backend | Model | Notes |\n|---|---|---|---|\n`;
	for (const [name, c] of Object.entries(reg.classifiers ?? {})) {
		md += `| ${code(name)} | ${code(c.backend ?? '')} | ${c.model ? code(c.model) : ''} | ${esc(c.description ?? '')} |\n`;
	}
	return md;
}

// ---------------------------------------------------------------------------

function write(rel, content) {
	const f = path.join(docs, rel);
	fs.mkdirSync(path.dirname(f), { recursive: true });
	fs.writeFileSync(f, content);
	return rel;
}

export function generate() {
	const results = JSON.parse(fs.readFileSync(path.resolve(here, '../src/data/template-results.json'), 'utf8'));
	const tpls = loadTemplates();
	const tplDir = path.join(docs, 'templates');
	fs.rmSync(tplDir, { recursive: true, force: true });
	const written = [];
	written.push(write('templates/index.mdx', templatesIndex(tpls)));
	for (const t of tpls) written.push(write(`templates/${t.wf.name}.mdx`, templatePage(t, results.templates)));

	// skills table goes into a data file the hand-written page imports? Keep it simple: a
	// generated partial page under skills/ plus the hand-written overview.
	const skills = loadSkills();
	let sk = `---\ntitle: Skill catalogue\ndescription: Every agent skill in skills/, generated from each SKILL.md.\n---\n\n`;
	sk += BANNER('skills/*/SKILL.md');
	sk += `\n${skills.length} skills ship in [\`skills/\`](https://github.com/muthuishere/wfnexus/tree/main/skills). \`wfx install --skills\` copies every one into \`~/.claude\` and \`~/.agents\`.\n\n| Skill | What it does |\n|---|---|\n`;
	for (const s of skills) sk += `| [${code(s.name)}](https://github.com/muthuishere/wfnexus/blob/main/skills/${s.dir}/SKILL.md) | ${esc(s.description)} |\n`;
	written.push(write('skills/catalogue.mdx', sk));

	written.push(write('reference/cli.mdx', cliPage()));
	written.push(write('providers/registry.mdx', registryPage()));
	console.log(`generated ${written.length} pages: ${tpls.length} templates, ${skills.length} skills, CLI, registry`);
	return written;
}

if (import.meta.url === `file://${process.argv[1]}`) generate();
