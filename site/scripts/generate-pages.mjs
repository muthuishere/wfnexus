#!/usr/bin/env node
// Generate the pages that must never drift from the repo, from the repo itself:
//
//   templates/*/workflow.yaml, templates/*.yaml  → src/content/docs/templates/<name>.mdx (+ index)
//   skills/*/SKILL.md frontmatter                → src/content/docs/skills.mdx (the table)
//   registries.json                              → src/content/docs/providers/registry.mdx
//   the usage text `wfx help` prints             → src/content/docs/reference/cli.mdx
//
// Runs as `prebuild`, so `npm run build` always renders what is on disk. Hand-written prose
// lives in src/content/docs; generated pages carry a "generated" banner and are gitignored
// nowhere — they are rebuilt on every build, so an edit to them is lost by design.
//
// Real results per template live in src/data/template-results.json: each one names the commit
// or PR it came from, and verify-symbols.mjs checks those commits exist.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const here = path.dirname(fileURLToPath(import.meta.url));
export const repoRoot = path.resolve(here, '../..');
const docs = path.resolve(here, '../src/content/docs');
const R = (p) => path.join(repoRoot, p);

const BANNER = (src) =>
	`{/* GENERATED by site/scripts/generate-pages.mjs from ${src.replace(/\*\//g, "*∕")}. Do not edit: the next build overwrites it. */}\n`;

/** Escape text for MDX body (braces and angle brackets are JSX in MDX). */
const esc = (s) =>
	String(s ?? '')
		.replace(/\\/g, '\\\\')
		.replace(/[{}]/g, (c) => (c === '{' ? '&#123;' : '&#125;'))
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/\|/g, '\\|')
		.replace(/\s*\n\s*/g, ' ')
		.trim();
const code = (s) => '`' + String(s).replace(/`/g, "'") + '`';
const yamlStr = (s) => JSON.stringify(String(s ?? '').replace(/\s+/g, ' ').trim());

// ---------------------------------------------------------------------------
// templates
// ---------------------------------------------------------------------------

export function templateFiles() {
	return fs
		.readdirSync(R('templates'))
		.sort()
		.map((d) => (d.endsWith('.yaml') ? `templates/${d}` : `templates/${d}/workflow.yaml`))
		.filter((f) => fs.existsSync(R(f)));
}

export function loadTemplates() {
	return templateFiles().map((file) => ({ file, wf: YAML.parse(fs.readFileSync(R(file), 'utf8')) }));
}

function stepKind(s) {
	if (s.run) return /\bwfx judge\b/.test(s.run) ? 'shell + classifier (`wfx judge`)' : 'shell (`run:`)';
	if (s.judge) return 'classifier (`judge:`)';
	if (s.team) return `agent team (${s.team.length})`;
	if (s.uses || s.use) return 'task (`use:`)';
	return 'agent';
}

function gatesOf(s) {
	const out = [];
	for (const g of s.gates ?? []) {
		const act = g.action === 'skip_to' ? `skip to ${code(g.skip_to)}` : g.action;
		out.push(`${code(g.field)} = ${code(JSON.stringify(g.equals))} → ${act}`);
	}
	if (s.decide?.gates) for (const g of s.decide.gates) out.push(`decide ${code(g.question)} → ${g.action}`);
	return out;
}

function triggers(on) {
	if (!on) return 'manual only (`wfx run`)';
	const t = [];
	if ('workflow_dispatch' in on || 'dispatch' in on) t.push('manual (`wfx run`)');
	for (const s of on.schedule ?? []) t.push(`schedule ${code(s.cron)}`);
	if (on.repository_dispatch) t.push(`repository_dispatch ${(on.repository_dispatch.types ?? []).map(code).join(', ')}`);
	return t.join(' · ') || 'manual only (`wfx run`)';
}

function templatePage({ file, wf }, results) {
	const t = typeof wf.template === 'object' ? wf.template : {};
	const title = t.title || wf.name;
	const steps = wf.steps ?? [];
	const props = wf.input_schema?.properties ?? {};
	const required = new Set(wf.input_schema?.required ?? []);
	const approvals = steps.filter((s) => s.requires_approval);
	const asks = steps.filter((s) => (s.tools ?? []).includes('ask_human') || s.ask_human);
	const needsInput = steps.flatMap((s) => (s.gates ?? []).filter((g) => g.action === 'needs_input').map((g) => ({ s, g })));
	const providers = [...new Set(steps.map((s) => s.provider).filter(Boolean))];
	const res = results[wf.name];

	let md = `---\ntitle: ${yamlStr(wf.name)}\ndescription: ${yamlStr(t.summary || wf.description)}\n---\n\n`;
	md += `import { Aside } from '@astrojs/starlight/components';\n\n`;
	md += BANNER(file);
	md += `\n**${esc(title)}**\n\n${esc(t.summary || wf.description)}\n\n`;
	md += `| | |\n|---|---|\n`;
	md += `| Source | [${code(file)}](https://github.com/muthuishere/wfnexus/blob/main/${file}) |\n`;
	md += `| Category | ${t.category ? code(t.category) : '—'} |\n`;
	md += `| Trigger | ${triggers(wf.on)} |\n`;
	md += `| Steps | ${steps.length} |\n`;
	md += `| Human approval before | ${approvals.length ? approvals.map((s) => code(s.id)).join(', ') : 'none'} |\n`;
	md += `| Providers named | ${providers.length ? providers.map(code).join(', ') : 'default (`WFX_DEFAULT_PROVIDER`)'} |\n\n`;

	md += `## Use it\n\n\`\`\`bash\nwfx templates ${wf.name}\nwfx new ${wf.name} --as my-${wf.name}\nwfx dryrun my-${wf.name}\n\`\`\`\n\n`;

	if (wf.description && t.summary) md += `## What it does\n\n${esc(wf.description)}\n\n`;

	if (t.fill?.length) {
		md += `## What you fill in\n\n`;
		for (const f of t.fill) md += `- ${esc(f)}\n`;
		md += `\n`;
	}

	if (Object.keys(props).length) {
		md += `## Inputs\n\n| Input | Type | Default | Required | Meaning |\n|---|---|---|---|---|\n`;
		for (const [k, v] of Object.entries(props)) {
			md += `| ${code(k)} | ${esc(v.type ?? '')} | ${v.default === undefined ? '' : code(JSON.stringify(v.default))} | ${required.has(k) ? 'yes' : ''} | ${esc(v.description ?? '')} |\n`;
		}
		md += `\n`;
	}

	md += `## Steps\n\n| # | Step | Kind | Skills | Gates |\n|---|---|---|---|---|\n`;
	steps.forEach((s, i) => {
		const g = gatesOf(s);
		if (s.requires_approval) g.unshift('**human approval first**');
		md += `| ${i + 1} | ${code(s.id)}${s.name && s.name !== s.id ? `<br/>${esc(s.name)}` : ''} | ${stepKind(s)}${s.provider ? `<br/>on ${code(s.provider)}` : ''} | ${(s.skills ?? []).map(code).join(' ')} | ${g.join('<br/>')} |\n`;
	});
	md += `\n`;

	md += `## Human gates\n\n`;
	if (!approvals.length && !needsInput.length && !asks.length) md += `This template never stops for a person.\n\n`;
	for (const s of approvals) md += `- **${code(s.id)}** waits for \`wfx approve <run-id>\` (or \`wfx reject <run-id> -m "why"\`) before it runs.\n`;
	for (const { s, g } of needsInput) md += `- **${code(s.id)}** pauses for input when ${code(g.field)} is ${code(JSON.stringify(g.equals))}${g.message ? `: “${esc(g.message)}”` : ''}. Resume with \`wfx answer <run-id> -m "..."\`.\n`;
	for (const s of asks) md += `- **${code(s.id)}** may call \`ask_human\`; answer with \`wfx answer <run-id> -m "..."\`.\n`;
	md += `\n`;

	md += `## Real result\n\n`;
	if (res) md += `${res.text}\n\n`;
	else md += `<Aside type="note" title="No recorded run">No run of this template is recorded in the repository's history yet, so this page makes no claim about results.</Aside>\n`;
	return md;
}

function templatesIndex(tpls) {
	let md = `---\ntitle: Templates\ndescription: Every workflow template that ships in templates/, generated from its YAML.\n---\n\n`;
	md += BANNER('templates/');
	md += `\nA template is a workflow with a \`template:\` block: a title, a summary, a category and the\nthings you must fill in. \`wfx templates\` lists them; \`wfx new <template> --as <name>\` copies one into\na workflow of your own. Every page in this section is generated from the YAML on each build, so\nthe step lists cannot drift from the files.\n\n`;
	md += `| Template | Category | Steps | Human approval | Summary |\n|---|---|---|---|---|\n`;
	for (const { wf } of tpls) {
		const t = typeof wf.template === 'object' ? wf.template : {};
		const steps = wf.steps ?? [];
		md += `| [${wf.name}](./${wf.name}/) | ${t.category ? code(t.category) : ''} | ${steps.length} | ${steps.filter((s) => s.requires_approval).length} | ${esc(t.title || wf.description)} |\n`;
	}
	return md;
}

